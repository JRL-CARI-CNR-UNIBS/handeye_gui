"""Write a calibration as a ROS 2 launch file or a YAML file."""

from __future__ import annotations

from pathlib import Path
from typing import Sequence

import yaml

LAUNCH_TEMPLATE = '''"""Hand-eye calibration (eye-in-hand) generated by handeye_gui."""
from launch import LaunchDescription
from launch_ros.actions import Node


def generate_launch_description() -> LaunchDescription:
    return LaunchDescription([
        Node(
            package="tf2_ros",
            executable="static_transform_publisher",
            name="handeye_{child_name}",
            output="log",
            arguments=[
                "--frame-id", "{parent}",
                "--child-frame-id", "{child}",
                "--x", "{x:.8f}", "--y", "{y:.8f}", "--z", "{z:.8f}",
                "--qx", "{qx:.8f}", "--qy", "{qy:.8f}", "--qz", "{qz:.8f}", "--qw", "{qw:.8f}",
            ],
        ),
    ])
'''


def write_calibration(path: str | Path, parent: str, child: str, pose7: Sequence[float]) -> None:
    """Write ``parent -> child`` as a launch file (.py) or YAML (anything else)."""
    path = Path(path)
    x, y, z, qx, qy, qz, qw = (float(v) for v in pose7)
    if path.suffix == ".py":
        child_name = "".join(c if c.isalnum() else "_" for c in child)
        path.write_text(LAUNCH_TEMPLATE.format(parent=parent, child=child, child_name=child_name,
                                               x=x, y=y, z=z, qx=qx, qy=qy, qz=qz, qw=qw))
    else:
        with open(path, "w") as stream:
            yaml.safe_dump({"parent_frame": parent, "child_frame": child,
                            "translation": {"x": x, "y": y, "z": z},
                            "rotation": {"x": qx, "y": qy, "z": qz, "w": qw}},
                           stream, sort_keys=False)
